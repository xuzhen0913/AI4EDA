"""The one shared testbench. References hold only the circuit; this module wraps it.

Conditions, library, supply, reference input, feedback loop, AC source, load, DC diagnostics and AC measurements are
generated here from the specs and from the circuit's own devices and nodes, so no reference repeats them and every
topology is measured in exactly the same way.

Biasing and measuring are separated the way they are on a bench. The DC operating point is found with unity negative
feedback closed from `out` to one input (the loop sits in an inductor that is a short at DC), so the output rests at
VCM exactly as in real use instead of wherever a tiny open-loop imbalance pushes it. The same inductor is an open
circuit at every swept frequency, so the AC analysis sees the OPEN loop: 1 V of AC is injected at the feedback input
through a capacitor that blocks DC, and the loop gain is T = -V(out)/V(injected).
"""
from analog_agents.spice import circuit_nodes, logical_lines, mos_devices

PORTS = ('vdd', 'vinp', 'vinn', 'out')
FEEDBACK_INPUTS = ('vinp', 'vinn')
RESERVED_PARAMS = ('VDD', 'VCM', 'CLOAD')
RESERVED_ELEMENTS = ('VSUPPLY', 'VINP', 'VINN', 'CLOAD_OUT', 'LFB', 'VAC', 'CAC')
RESERVED_NODES = ('acin',)
FORBIDDEN_STATEMENTS = ('.lib', '.temp', '.control', '.endc', '.end', '.include', '.nodeset', '.ic')
PROPERTIES = ('id', 'gm', 'gds', 'vgs', 'vds', 'vth', 'vdsat')
LOOP_POLARITY = 'loop_real_lf'
LOOP_INDUCTANCE = '1e9'        # H: far above any impedance in the circuit at the lowest swept frequency
INJECTION_CAPACITANCE = '1e3'  # F: far below any impedance in the circuit at the lowest swept frequency


def check_circuit(text):
    """A reference must be the circuit only, with the four testbench ports."""
    for line in logical_lines(text):
        first = line.split()[0]
        if first.lower() in FORBIDDEN_STATEMENTS:
            raise ValueError(f'{first} belongs to the shared testbench, not to a reference')
        if first.upper() in RESERVED_ELEMENTS:
            raise ValueError(f'{first} is generated by the shared testbench; remove it from the reference')
        if first.lower() == '.param' and line.split()[1].split('=')[0].upper() in RESERVED_PARAMS:
            raise ValueError(f'{line.split()[1]} is defined by the shared testbench (from the specs)')
    nodes = circuit_nodes(text)
    missing = [p for p in PORTS if p not in nodes]
    if missing:
        raise ValueError('Circuit must use the testbench ports vdd, vinp, vinn, out; missing: ' + ', '.join(missing))
    if any(n in nodes for n in RESERVED_NODES):
        raise ValueError('Node name(s) ' + ', '.join(RESERVED_NODES) + ' are used by the shared testbench')


def number_text(value):
    return f'{value:.10g}'


def deck(circuit, specs, library, mode='full', feedback_input='vinp'):
    """Complete ngspice deck: closed-loop DC operating point always, open-loop AC measurements only in `full` mode.

    `feedback_input` is the input that closes the loop (the circuit's inverting input, declared by its reference);
    the other input is the fixed reference at VCM.
    """
    if mode not in ('dc', 'full'):
        raise ValueError('Unknown analysis mode')
    if feedback_input not in FEEDBACK_INPUTS:
        raise ValueError(f'feedback_input must be one of {FEEDBACK_INPUTS}, not {feedback_input!r}')
    held = FEEDBACK_INPUTS[1 - FEEDBACK_INPUTS.index(feedback_input)]
    c, sweep = specs['conditions'], specs['ac_validation']['sweep']
    lines = [f'* op-amp testbench ({mode}): generated, not edited by hand',
             f'.lib "{library}" {specs["corner"]}', f'.temp {number_text(c["temperature_c"])}',
             f'.param VDD={number_text(c["vdd_v"])}', f'.param VCM={number_text(c["input_common_mode_v"])}',
             f'.param CLOAD={number_text(c["load_capacitance_f"])}', circuit.rstrip(),
             'VSUPPLY vdd 0 {VDD}', f'{held.upper()} {held} 0 DC {{VCM}}',
             f'LFB out {feedback_input} {LOOP_INDUCTANCE}',
             'VAC acin 0 DC 0 AC 1', f'CAC acin {feedback_input} {INJECTION_CAPACITANCE}',
             'CLOAD_OUT out 0 {CLOAD}', f'.nodeset v(out)={number_text(c["input_common_mode_v"])}',
             '.control', 'set noaskquit', 'set numdgt=10', 'op', 'echo DC_OPERATING_POINT']
    lines += [f'print v({node})' for node in circuit_nodes(circuit)]
    lines += ['let supply_current_a = -i(VSUPPLY)', 'let power_w = -i(VSUPPLY)*v(vdd)', 'print supply_current_a power_w']
    for device in mos_devices(circuit).values():
        lines += [f'print {device["diagnostic_prefix"]}[{p}]' for p in PROPERTIES]
    lines.append('echo END_DC_OPERATING_POINT')
    if mode == 'full':
        start = number_text(sweep['start_hz'])
        lines += [f'ac dec {sweep["points_per_decade"]} {start} {number_text(sweep["stop_hz"])}',
                  'let loop_gain = -v(out)/v(acin)', 'let gain = db(loop_gain)',
                  'let loop_phase_deg = 180/PI*cph(loop_gain)', 'let loop_real = real(loop_gain)',
                  f'meas ac {LOOP_POLARITY} FIND loop_real AT={start}', f'meas ac dc_gain_db FIND gain AT={start}',
                  'meas ac ugb_hz WHEN gain=0 FALL=1', 'meas ac phase_at_ugb FIND loop_phase_deg WHEN gain=0 FALL=1',
                  'let phase_margin_deg = 180+phase_at_ugb', 'print phase_margin_deg']
    lines += ['quit', '.endc', '.end']
    return '\n'.join(lines) + '\n'


def describe(specs, feedback_input=None):
    """The same facts as `deck`, in words, for the agents (single source: the specs and this module)."""
    c, s, d = specs['conditions'], specs['ac_validation']['sweep'], specs.get('dc_acceptance', {})
    vcm = c['input_common_mode_v']
    where = f'the {feedback_input} input' if feedback_input else "the circuit's inverting input (declared by each reference)"
    window = d.get('maximum_output_error_v')
    regulated = (f'; the loop must hold out within {window} V of it, otherwise the operating point is not regulated '
                 '(positive feedback or a saturated stage)') if window is not None else ''
    return (f'Fixed shared testbench, generated by the toolchain and not part of the netlist: process {specs["process"]}, '
            f'corner {specs["corner"]}, {c["temperature_c"]} C. Supply {c["vdd_v"]} V on node vdd; load {c["load_capacitance_f"]} F '
            f'from out to ground; the input that is not in the loop is held at {vcm} V. '
            f'DC operating point with unity negative feedback closed from out to {where} (an inductor, short at DC), so the '
            f'output rests at {vcm} V as in real use{regulated}. '
            f'AC then measures the OPEN loop (the inductor is open at AC): 1 V AC is injected at {where} through a DC-blocking '
            f'capacitor, sweep {s["start_hz"]:g}..{s["stop_hz"]:g} Hz, and the loop gain is T = -V(out)/V(injected), which is '
            f'positive-real at low frequency when the feedback is negative. dc_gain_db = 20log10|T| at {s["start_hz"]:g} Hz; '
            'ugb_hz = first falling 0 dB crossing of |T|; phase_margin_deg = 180 + phase(T) there (small-signal estimate, not a '
            'general stability proof); power_w = VDD * supply current. If T is not positive at low frequency the feedback is not '
            'negative (wrong input) or the gain is zero, and the AC result is invalid.')
